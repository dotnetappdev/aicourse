# variables.py — Module 02

# The four basic data types
name        = "Alice"    # str
age         = 30         # int
temperature = 98.6       # float
is_learning = True       # bool

# Print each value
print(name)
print(age)
print(temperature)
print(is_learning)

# Check types
print(type(name))
print(type(age))
print(type(temperature))
print(type(is_learning))

# Updating variables
score = 0
print(score)   # 0

score = 10
print(score)   # 10

score = score + 5
print(score)   # 15
